  /// Shared dimensions for a future verified region; does not register it with rendering.
  static func sourceRect(x: Double, y: Double, width: Double, height: Double) -> TextureSourceRect {
    .init(x: x, y: y, width: width, height: height, sheetWidth: Self.width, sheetHeight: Self.height)
  }

  static func isValid(_ rect: TextureSourceRect) -> Bool {
    [rect.x, rect.y, rect.width, rect.height, rect.sheetWidth, rect.sheetHeight].allSatisfy(\.isFinite)
      && rect.sheetWidth == width && rect.sheetHeight == height
      && rect.x >= 0 && rect.y >= 0 && rect.width > 0 && rect.height > 0
      && rect.x + rect.width <= width && rect.y + rect.height <= height
  }
